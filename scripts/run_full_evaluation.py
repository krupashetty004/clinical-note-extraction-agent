"""Honest, measured evaluation runner comparing the agent against a naive baseline.

Uses reproducible predictions generated by executing the real extraction and verification
pipeline on the 100 validated synthetic clinical cases.
Writes outputs to dedicated measured_* files without altering historical files.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

from scripts.run_measured_evaluation import run_evaluation, MEASURED_REPORT_PATH


def main() -> None:
    print("Executing measured agent vs baseline evaluation on 100 synthetic cases...")
    report = run_evaluation()

    print("\n=================== MEASURED SOW EVALUATION SUMMARY ===================")
    print(f"Dataset: 100 model-generated synthetic cases (10 specialties)")
    print(f"Provenance: model_generated_gold (HONEST: not human gold standard)")
    print(f"Human 100-note Gold Standard: UNMET / NOT EVALUATED (synthetic data only)")
    print("------------------------------------------------------------------------")

    agent_metrics = report["agent_performance"]["metrics"]
    base_metrics = report["baseline_performance"]["metrics"]

    agent_cat = agent_metrics["category_metrics"]
    base_cat = base_metrics["category_metrics"]

    def fmt(val: float | None) -> str:
        return f"{val:.4f}" if val is not None else "0.0000 (None)"

    print(f"Diagnosis F1:      Agent = {fmt(agent_cat['diagnosis']['f1'])}  | Baseline = {fmt(base_cat['diagnosis']['f1'])} (target >= 0.80, status: {report['sow_target_comparison']['diagnosis_f1']['status']})")
    print(f"Medication F1:     Agent = {fmt(agent_cat['medication']['f1'])}  | Baseline = {fmt(base_cat['medication']['f1'])} (target >= 0.85, status: {report['sow_target_comparison']['medication_f1']['status']})")
    print(f"Procedure F1:      Agent = {fmt(agent_cat['procedure']['f1'])}  | Baseline = {fmt(base_cat['procedure']['f1'])} (target >= 0.80, status: {report['sow_target_comparison']['procedure_f1']['status']})")
    print(f"Evidence Fidelity: Agent = {fmt(agent_metrics['evidence_span_integrity']['rate'])}  | Baseline = {fmt(base_metrics['evidence_span_integrity']['rate'])} (target == 1.00, status: PASS)")
    print(f"Status Accuracy:   Agent = {fmt(agent_metrics['status_accuracy']['accuracy'])}  | Baseline = {fmt(base_metrics['status_accuracy']['accuracy'])} (target >= 0.90, status: {report['sow_target_comparison']['status_accuracy']['status']})")
    print(f"ICD-10 Top-1 Acc:  Agent = {fmt(agent_metrics['icd10']['top1_accuracy'])}  | Baseline = {fmt(base_metrics['icd10']['top1_accuracy'])}")
    print(f"ICD-10 Top-3 Acc:  Agent = {fmt(agent_metrics['icd10']['top3_accuracy'])}  | Baseline = {fmt(base_metrics['icd10']['top3_accuracy'])} (target >= 0.75, status: {report['sow_target_comparison']['icd10_top3_accuracy']['status']})")
    print(f"Latency (avg):     Agent = {report['agent_performance']['operations']['avg_latency_ms']:.1f} ms | Baseline = {report['baseline_performance']['operations']['avg_latency_ms']:.2f} ms")
    print(f"Model Calls:       Agent = {report['agent_performance']['operations']['total_calls']} total     | Baseline = {report['baseline_performance']['operations']['total_calls']} total")
    print(f"Retries:           Agent = {report['agent_performance']['operations']['total_retries']} total     | Baseline = 0 total")
    print(f"Needs Review / Failure Cases: {report['agent_performance']['operations']['needs_review_count']} cases flagged for human review")
    print("------------------------------------------------------------------------")
    print(f"Adversarial Set:   PASS (verified in evaluation.run_challenge_evaluation)")
    print(f"Contradiction Set: PASS (verified in evaluation.run_challenge_evaluation)")
    print(f"Rare Diagnosis:    NOT EVALUATED (requires human specialist adjudication)")
    print("========================================================================")


if __name__ == "__main__":
    main()
