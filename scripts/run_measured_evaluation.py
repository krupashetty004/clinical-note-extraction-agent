"""Run honest, measured evaluation comparing the agent against a naive baseline.

Uses reproducible predictions generated by executing the real extraction and verification
pipeline on the 100 validated synthetic clinical cases.
Writes outputs to dedicated measured_* files without altering historical files.
"""
from __future__ import annotations

import json
import time
import sys
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT))

# Setup Django settings for models access
import os
import django
os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
django.setup()

from evaluation.metrics import evaluate_dataset
from mirai_dataset_preparation_pack.scripts.validate_annotations import (
    evaluation_cases_from_records,
    load_icd_reference,
)
from dashboard.extraction.local_provider import (
    LocalClinicalExtractionProvider,
    LocalClinicalVerificationProvider,
)
